#!/usr/bin/env sh
#
# The recette stack's runtime secrets, generated once per machine (SEC-22).
#
# compose.recette.yaml used to commit them, and the recette can be exposed over ngrok
# (scripts/ngrok-recette.sh): anyone reading the public repository could then mint Mercure
# tokens or forge signed URLs against that tunnel. They now live in an untracked env file,
# read by every recette compose call through `--env-file .env --env-file .env.recette`.
#
# Usage: generate-recette-secrets.sh [<file>]   (default: .env.recette)
#
# An existing file is left alone: regenerating REFRESH_TOKEN_ENC_KEY or OAUTH_ENCRYPTION_KEY
# would log out every recette session. Delete the file to rotate.
set -eu

FILE="${1:-.env.recette}"

if [ -f "$FILE" ]; then
	exit 0
fi

secret() { openssl rand -hex 32; }

umask 077
{
	echo '# Generated by scripts/generate-recette-secrets.sh. Untracked; delete to rotate.'
	echo "RECETTE_APP_SECRET=$(secret)"
	echo "RECETTE_MERCURE_JWT_KEY=$(secret)"
	echo "RECETTE_REFRESH_TOKEN_ENC_KEY=$(secret)"
	echo "RECETTE_OAUTH_ENCRYPTION_KEY=$(secret)"
	echo "RECETTE_ACCESS_REQUEST_HMAC_SECRET=$(secret)"
} > "$FILE"

echo "$FILE: recette secrets written"
